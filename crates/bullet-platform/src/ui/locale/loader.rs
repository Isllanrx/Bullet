pub(super) fn load(lang: Language) -> &'static Text {
    let Some((idx, json)) = slot_and_json(lang) else {
        return &ENGLISH;
    };
    CACHE[idx].get_or_init(|| Box::leak(Box::new(parse_or_fallback(json))))
}

fn take(map: &mut HashMap<String, String>, key: &str, fallback: &'static str) -> &'static str {
    match map.remove(key) {
        Some(value) if !value.is_empty() => Box::leak(value.into_boxed_str()),
        _ => fallback,
    }
}

macro_rules! build_text {
    ($map:expr, $fallback:expr, [$($field:ident),* $(,)?]) => {
        Text {
            $($field: take(&mut $map, stringify!($field), $fallback.$field),)*
        }
    };
}

